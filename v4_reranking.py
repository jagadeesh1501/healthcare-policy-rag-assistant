import logging
import os
import time
from functools import lru_cache
from pathlib import Path

from langchain_community.vectorstores import FAISS
from sentence_transformers import CrossEncoder

from rag_common import (
    load_chunks,
    get_embeddings,
    answer_with_docs,
    VECTOR_DIR,
    RETRIEVER_K,
    RERANK_TOP_N,
)

# --------------------------------------------------
# CONFIGURATION
# --------------------------------------------------

RERANKER_MODEL = os.getenv(
    "RERANKER_MODEL",
    "cross-encoder/ms-marco-MiniLM-L-6-v2",
)

# Keep V4's index separate from V2's FAISS index.
FAISS_DIR = Path(VECTOR_DIR) / "faiss_v4"

# Keep the first-stage retrieval modest for small cloud instances.
CANDIDATE_K = max(1, int(os.getenv("CANDIDATE_K", "8")))
RERANK_BATCH_SIZE = max(1, int(os.getenv("RERANK_BATCH_SIZE", "4")))

# Shorter input sequences reduce Cross-Encoder inference time.
RERANKER_MAX_LENGTH = max(128, int(os.getenv("RERANKER_MAX_LENGTH", "384")))

FALLBACK_ANSWER = (
    "I couldn't find sufficient information in the provided documents."
)

# --------------------------------------------------
# LOGGING
# --------------------------------------------------

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
)
logger = logging.getLogger(__name__)


def log_time(stage, start_time):
    """Log and return elapsed seconds for a pipeline stage."""
    elapsed = time.perf_counter() - start_time
    logger.info("[V4] %s completed in %.2f seconds", stage, elapsed)
    return elapsed


# --------------------------------------------------
# EMBEDDINGS AND RERANKER
# --------------------------------------------------

@lru_cache(maxsize=1)
def get_reranker():
    """Load the Cross-Encoder on first use and cache it for later questions."""
    start = time.perf_counter()
    logger.info(
        "[V4] Loading Cross-Encoder model '%s' (max_length=%s)",
        RERANKER_MODEL,
        RERANKER_MAX_LENGTH,
    )
    model = CrossEncoder(RERANKER_MODEL, max_length=RERANKER_MAX_LENGTH)
    log_time("Cross-Encoder initialization", start)
    return model


# --------------------------------------------------
# FAISS INDEX
# --------------------------------------------------

@lru_cache(maxsize=1)
def load_or_create_index():
    """Load the saved V4 index or create it from PDFs, then cache it in memory."""
    overall_start = time.perf_counter()
    logger.info("[V4] Starting FAISS index initialization")

    embedding_start = time.perf_counter()
    embeddings = get_embeddings()
    log_time("Embedding model initialization", embedding_start)

    index_file = FAISS_DIR / "index.faiss"
    metadata_file = FAISS_DIR / "index.pkl"

    if index_file.is_file() and metadata_file.is_file():
        logger.info("[V4] Loading existing FAISS index from %s", FAISS_DIR)
        load_start = time.perf_counter()
        db = FAISS.load_local(
            str(FAISS_DIR),
            embeddings,
            # Safe only because this is an index generated by this project.
            allow_dangerous_deserialization=True,
        )
        log_time("FAISS index loading", load_start)
        logger.info("[V4] FAISS index ready; indexed chunks=%d", db.index.ntotal)
        log_time("Total index initialization", overall_start)
        return db

    logger.warning(
        "[V4] Saved index not found at %s. Building an index from PDFs; "
        "this first run may take several minutes.",
        FAISS_DIR,
    )

    pdf_start = time.perf_counter()
    chunks = load_chunks()
    log_time("PDF loading and chunking", pdf_start)

    if not chunks:
        raise ValueError(
            "No document chunks were created. Check that PDF files exist "
            "inside the configured PDF_DIR/data folder."
        )

    logger.info("[V4] Creating FAISS index from %d chunks", len(chunks))
    build_start = time.perf_counter()
    db = FAISS.from_documents(documents=chunks, embedding=embeddings)
    log_time("FAISS index creation and embedding", build_start)

    save_start = time.perf_counter()
    FAISS_DIR.mkdir(parents=True, exist_ok=True)
    db.save_local(str(FAISS_DIR))
    log_time("FAISS index save", save_start)

    logger.info("[V4] New FAISS index saved to %s", FAISS_DIR)
    logger.info("[V4] FAISS index ready; indexed chunks=%d", db.index.ntotal)
    log_time("Total index initialization", overall_start)
    return db


# --------------------------------------------------
# RETRIEVAL
# --------------------------------------------------

def retrieve_candidates(question, db):
    """Retrieve the most similar chunks from FAISS."""
    start = time.perf_counter()
    total_chunks = int(db.index.ntotal)

    if total_chunks <= 0:
        logger.warning("[V4] FAISS index contains no chunks")
        return []

    k = min(CANDIDATE_K, total_chunks)
    logger.info("[V4] Retrieving %d candidates from %d indexed chunks", k, total_chunks)
    docs = db.similarity_search(question, k=k)
    logger.info("[V4] Retrieved %d candidate chunks", len(docs))
    log_time("FAISS retrieval", start)
    return docs


# --------------------------------------------------
# CROSS-ENCODER RERANKING
# --------------------------------------------------

def rerank(question, docs, top_n=RERANK_TOP_N):
    """Rerank retrieved chunks with a Cross-Encoder and return the top results."""
    if not docs:
        logger.info("[V4] No candidate documents to rerank")
        return []

    start = time.perf_counter()
    model = get_reranker()
    pairs = [(question, doc.page_content) for doc in docs]
    logger.info("[V4] Reranking %d candidate chunks", len(pairs))

    scores = model.predict(
        pairs,
        batch_size=RERANK_BATCH_SIZE,
        show_progress_bar=False,
    )

    ranked_docs = sorted(
        zip(scores, docs),
        key=lambda item: float(item[0]),
        reverse=True,
    )
    selected_count = max(1, min(int(top_n), len(ranked_docs)))
    selected = [doc for _, doc in ranked_docs[:selected_count]]

    logger.info(
        "[V4] Reranking selected %d of %d chunks",
        len(selected),
        len(docs),
    )
    log_time("Cross-Encoder reranking", start)
    return selected


# --------------------------------------------------
# ASK A QUESTION
# --------------------------------------------------

def ask(question, db):
    """Run retrieval, reranking, and grounded answer generation.

    Returns seven values expected by streamlit_app.py:
    answer, sources, candidates, selected, retrieval_time,
    rerank_time, answer_time.
    """
    question = question.strip() if isinstance(question, str) else ""
    if not question:
        raise ValueError("Please enter a policy question.")

    question_start = time.perf_counter()
    logger.info("[V4] Starting question processing: %s", question[:200])

    # Stage 1: retrieval
    retrieval_start = time.perf_counter()
    candidates = retrieve_candidates(question, db)
    retrieval_time = time.perf_counter() - retrieval_start

    if not candidates:
        logger.warning("[V4] No candidates retrieved; returning fallback answer")
        return FALLBACK_ANSWER, [], [], [], retrieval_time, 0.0, 0.0

    # Stage 2: reranking
    rerank_start = time.perf_counter()
    selected = rerank(question, candidates, top_n=RERANK_TOP_N)
    rerank_time = time.perf_counter() - rerank_start

    if not selected:
        logger.warning("[V4] Reranker returned no chunks; returning fallback answer")
        return FALLBACK_ANSWER, [], candidates, [], retrieval_time, rerank_time, 0.0

    # Stage 3: Gemini answer generation
    answer_start = time.perf_counter()
    logger.info(
        "[V4] Starting answer generation with %d selected chunks; "
        "the model/API call may take time.",
        len(selected),
    )
    try:
        answer, sources = answer_with_docs(question, selected)
    except Exception:
        logger.exception("[V4] Answer generation failed")
        raise
    answer_time = time.perf_counter() - answer_start

    total_time = time.perf_counter() - question_start
    logger.info(
        "[V4] Question complete | retrieval=%.2fs | reranking=%.2fs | "
        "answer=%.2fs | total=%.2fs",
        retrieval_time,
        rerank_time,
        answer_time,
        total_time,
    )

    return (
        answer,
        sources,
        candidates,
        selected,
        retrieval_time,
        rerank_time,
        answer_time,
    )


