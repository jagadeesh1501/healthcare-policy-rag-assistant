if __name__ == "__main__":
    try:
        logger.info("[V4] Starting Healthcare Policy RAG Assistant")
        startup_start = time.perf_counter()
        db = load_or_create_index()
        log_time("Application index startup", startup_start)

        print("\nHealthcare Policy RAG Assistant — V4")
        print("FAISS retrieval + Cross-Encoder reranking")
        print("Type 'exit' to stop.\n")

        while True:
            question = input("Ask a policy question: ").strip()
            if question.lower() in {"exit", "quit"}:
                print("Exiting Healthcare Policy RAG Assistant.")
                break
            if not question:
                print("Please enter a question.\n")
                continue

            try:
                (
                    answer,
                    sources,
                    candidates,
                    selected,
                    retrieval_time,
                    rerank_time,
                    answer_time,
                ) = ask(question, db)

                print("\n" + "=" * 60)
                print("ANSWER")
                print("=" * 60)
                print(answer)

                print("\n" + "-" * 60)
                print("RETRIEVAL AND RERANKING DETAILS")
                print("-" * 60)
                print(f"Candidate chunks retrieved : {len(candidates)}")
                print(f"Chunks selected by reranker: {len(selected)}")
                print(f"FAISS retrieval time       : {retrieval_time:.2f}s")
                print(f"Cross-Encoder rerank time  : {rerank_time:.2f}s")
                print(f"Answer generation time     : {answer_time:.2f}s")
                print(f"Total processing time      : {retrieval_time + rerank_time + answer_time:.2f}s")

                print("\n" + "-" * 60)
                print("SOURCES")
                print("-" * 60)
                if sources:
                    for source in sources:
                        print(
                            f"- {source['source']} | PDF page {source['page']} | "
                            f"{source['document_type']}"
                        )
                else:
                    print("No sources returned.")
                print()
            except Exception:
                logger.exception("[V4] Error processing question")
                print("\nUnable to process the question. Check the logs above.\n")

    except Exception:
        logger.exception("[V4] Could not start the application")
        print("\nCould not start V4. Check the logs, dependencies, configuration, and PDF files.")
